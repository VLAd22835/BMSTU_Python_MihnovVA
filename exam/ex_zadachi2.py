import math  # Импортируем модуль math для использования функции sqrt() (квадратный корень)


# ============================================================================
# ФУНКЦИЯ ПРОВЕРКИ ЧИСЛА НА ПРОСТОТУ
# ============================================================================

def is_prime(
        number):  # Определяем функцию с именем is_prime, которая принимает один параметр - number (проверяемое число)
    """
    Эта функция проверяет, является ли переданное число простым.
    Простое число - это число больше 1, которое делится только на 1 и на само себя.
    """

    # ------------------------------------------------------------------------
    # БЛОК 1: ПРОВЕРКА ОСОБЫХ СЛУЧАЕВ (числа меньше или равные 1)
    # ------------------------------------------------------------------------

    if number <= 1:  # Условие: если переданное число меньше или равно 1
        return False  # Возвращаем False, так как числа ≤ 1 не являются простыми по определению
        # (0, 1, отрицательные числа - НЕ простые)

    # ------------------------------------------------------------------------
    # БЛОК 2: ПРОВЕРКА НА ЧИСЛО 2 (единственное чётное простое число)
    # ------------------------------------------------------------------------

    if number == 2:  # Условие: если число равно 2
        return True  # Возвращаем True, так как 2 - это простое число
        # 2 - особый случай, так как это единственное чётное простое число

    # ------------------------------------------------------------------------
    # БЛОК 3: ОПТИМИЗАЦИЯ - ОТСЕИВАНИЕ ВСЕХ ОСТАЛЬНЫХ ЧЁТНЫХ ЧИСЕЛ
    # ------------------------------------------------------------------------

    if number % 2 == 0:  # Проверяем, делится ли число на 2 без остатка (остаток от деления на 2 равен 0)
        # Оператор % возвращает остаток от деления. Например: 4 % 2 = 0, 5 % 2 = 1
        return False  # Возвращаем False, так как любое чётное число (кроме 2) делится на 2
        # Значит у него есть делитель 2, поэтому оно составное, а не простое

    # ------------------------------------------------------------------------
    # БЛОК 4: ОСНОВНАЯ ПРОВЕРКА ДЕЛИТЕЛЕЙ (самый важный блок!)
    # ------------------------------------------------------------------------

    # Вычисляем квадратный корень из числа и преобразуем в целое число (округляем вниз)
    # int() - отбрасывает дробную часть (например, int(5.8) = 5)
    # math.sqrt(number) - вычисляет квадратный корень из number
    limit = int(math.sqrt(number))  # Переменная limit хранит верхнюю границу проверки
    # Почему до корня? Если число N = a * b, то один из множителей обязательно ≤ √N
    # Например, для 36: √36 = 6, делители: 4 и 9 (4 ≤ 6, 9 ≥ 6)
    # Достаточно проверить до 6, чтобы найти все делители

    # Создаём цикл for для перебора возможных делителей
    # range(3, limit + 1, 2) - генерирует последовательность чисел:
    #   - Начало: 3 (начинаем с 3, так как 2 уже проверили в блоке 3)
    #   - Конец: limit + 1 (проверяем до limit включительно, range не включает последнее число)
    #   - Шаг: 2 (пропускаем чётные числа, так как их мы уже отсеяли в блоке 3)
    # Получаем последовательность: 3, 5, 7, 9, 11, 13, ... до limit
    for i in range(3, int(math.sqrt(number)) + 1, 2):
        # i - это текущий делитель, который мы проверяем (3, 5, 7, 9, ...)

        # --------------------------------------------------------------------
        # БЛОК 5: ПРОВЕРКА ДЕЛИМОСТИ
        # --------------------------------------------------------------------

        if number % i == 0:  # Проверяем, делится ли number на i без остатка
            # Оператор % снова вычисляет остаток от деления
            # Если остаток равен 0, значит число делится на i нацело
            return False  # Возвращаем False, так как нашли делитель
            # Это значит, что число составное (имеет делитель кроме 1 и самого себя)

    # ------------------------------------------------------------------------
    # БЛОК 6: ВОЗВРАТ РЕЗУЛЬТАТА (если ни один делитель не найден)
    # ------------------------------------------------------------------------

    return True  # Если цикл завершился и ни разу не сработал return False
    # значит мы не нашли ни одного делителя, следовательно число простое
    # Возвращаем True (число простое)


# ============================================================================
# ОСНОВНАЯ ЧАСТЬ ПРОГРАММЫ (ВВОД ДАННЫХ И ВЫВОД РЕЗУЛЬТАТА)
# ============================================================================

# ----------------------------------------------------------------------------
# БЛОК 7: ВВОД ЧИСЛА ОТ ПОЛЬЗОВАТЕЛЯ
# ----------------------------------------------------------------------------

num = int(input("Enter number: "))  # Запрашиваем у пользователя ввод числа
# input("Enter number: ") - выводит текст на экран и ждёт, пока пользователь введёт данные
# int() - преобразует введённую строку в целое число (например, "17" → 17)
# Результат сохраняется в переменную num

# ----------------------------------------------------------------------------
# БЛОК 8: ВЫЗОВ ФУНКЦИИ И ПРОВЕРКА УСЛОВИЯ
# ----------------------------------------------------------------------------

if is_prime(num):  # Вызываем функцию is_prime() с переданным числом num
    # Функция возвращает True (простое) или False (не простое)
    # if проверяет это значение: если True, то выполняет блок if
    # если False, то выполняет блок else

    # ------------------------------------------------------------------------
    # БЛОК 9: ВЫВОД РЕЗУЛЬТАТА (ЕСЛИ ЧИСЛО ПРОСТОЕ)
    # ------------------------------------------------------------------------

    print(f"{num} is prime")  # Выводим сообщение, что число простое
    # f-строка (f-string) позволяет вставлять переменные в текст
    # {num} подставляется значение переменной num
    # Например: если num = 17, выведет "17 is prime"

else:  # Блок else выполняется, если условие if было False (число НЕ простое)

    # ------------------------------------------------------------------------
    # БЛОК 10: ВЫВОД РЕЗУЛЬТАТА (ЕСЛИ ЧИСЛО НЕ ПРОСТОЕ)
    # ------------------------------------------------------------------------

    print(f"{num} is not prime")  # Выводим сообщение, что число НЕ простое
    # Например: если num = 4, выведет "4 is not prime"